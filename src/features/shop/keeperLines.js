/** A list, or the warm or cool half of a { warm, cool } list, by mood. */
export function byMood(list, mood) {
  if (!list || Array.isArray(list) || typeof list === "string") return list;
  return mood === "testy" || mood === "done" ? list.cool || list.warm : list.warm || list.cool;
}

/** A keeper's lines, falling back to Mags's for anything missing. */
